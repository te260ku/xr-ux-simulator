using System;
using System.Collections.Generic;
using System.Text;

public static class CSharpIdClassWriter
{
    public const string Marker = "// <auto-generated />\n// Generator: RepositoryIdGenerator\n";

    public static string Write(Type idType, Type targetType, IReadOnlyList<string> ids)
    {
        var result = new StringBuilder(Marker);
        result.AppendLine("// Do not edit this file. Regenerate it from the config asset.");
        var indent = string.IsNullOrEmpty(targetType.Namespace) ? "" : "    ";
        if (indent.Length > 0)
        {
            result.Append("namespace ").AppendLine(targetType.Namespace);
            result.AppendLine("{");
        }
        result.Append(indent).Append(GetModifiers(targetType))
            .Append("partial class ").AppendLine(targetType.Name);
        result.Append(indent).AppendLine("{");
        var typeName = GetTypeName(idType);
        foreach (var id in ids)
            AppendField(result, indent + "    ", typeName, id);
        result.Append(indent).AppendLine("}");
        if (indent.Length > 0) result.AppendLine("}");
        return result.ToString().Replace("\r\n", "\n");
    }

    private static string GetModifiers(Type type)
    {
        var access = type.IsPublic ? "public " : "internal ";
        if (type.IsAbstract && type.IsSealed) return access + "static ";
        if (type.IsAbstract) return access + "abstract ";
        if (type.IsSealed) return access + "sealed ";
        return access;
    }

    private static string GetTypeName(Type type)
    {
        return "global::" + type.FullName.Replace('+', '.');
    }

    private static void AppendField(StringBuilder result, string indent, string typeName, string id)
    {
        result.Append(indent).Append("public static readonly ").Append(typeName)
            .Append(' ').Append(id).Append(" = new ").Append(typeName)
            .Append("(\"").Append(Escape(id)).AppendLine("\");");
    }

    private static string Escape(string value)
    {
        return value.Replace("\\", "\\\\").Replace("\"", "\\\"")
            .Replace("\r", "\\r").Replace("\n", "\\n").Replace("\t", "\\t");
    }
}
